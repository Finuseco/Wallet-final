package com.example.data.model
import com.squareup.moshi.JsonClass
@JsonClass(generateAdapter=true)
data class ScanItem(val id:String,val quantity:Int=1,val name:String?=null,val sellingPrice:Double?=null)
@JsonClass(generateAdapter=true)
data class ScanInput(val type:String,val sellerWalletId:String?=null,val items:List<ScanItem>?=null,val recipient:String?=null,val amount:Double?=null,val currency:String?=null)
@JsonClass(generateAdapter=true)
data class ScanProduct(val id:String,val name:String,val price:Double,val currency:String,val stock:Int,val sellerWalletId:String,val sellerName:String,val boutiqueName:String?)
@JsonClass(generateAdapter=true)
data class ScanSale(val type:String,val sellerWalletId:String,val sellerName:String,val boutiqueName:String?=null,val amount:Double,val currency:String,val items:List<ScanItem> = emptyList())
@JsonClass(generateAdapter=true)
data class ScanQuote(val sale:ScanSale,val paymentCurrency:String,val debitAmount:Double,val fee:Double,val totalDebit:Double,val rate:Double,val quoteToken:String,val expiresAt:String)
@JsonClass(generateAdapter=true)
data class ScanResult(val type:String,val products:List<ScanProduct> = emptyList(),val scan:ScanInput?=null,val quote:ScanQuote?=null,val walletId:String?=null)
@JsonClass(generateAdapter=true)
data class ScanResponse(val success:Boolean,val scan:ScanResult?=null,val error:String?=null)
@JsonClass(generateAdapter=true)
data class ScanRequest(val value:String?=null,val action:String?=null,val scan:ScanInput?=null,val paymentCurrency:String?=null)
@JsonClass(generateAdapter=true)
data class ScanPaymentRequest(val quoteToken:String,val pin:String)
@JsonClass(generateAdapter=true)
data class ScanPaymentResponse(val success:Boolean,val reference:String?=null,val error:String?=null,val alreadyProcessed:Boolean=false)
